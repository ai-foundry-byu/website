"""Writes Scott's mark geometry (mark.py) and the regenerated blueprint (gen.py output) into the site.

    cd scripts/mark-motion && python3 gen.py af.css cons.tsx && python3 apply.py && rm af.css cons.tsx

Re-run both whenever the primary file in _brand-src/hex-diamond/marketing/primary changes."""
import math, re, sys
from pathlib import Path
from mark import LETTERS, HEX, CUT, GEOM
REPO = str(Path(__file__).resolve().parents[2]) + "/"
G = GEOM; W, H, CX, CY, R, D, HL, HR = (G[k] for k in "W H CX CY R D HL HR".split())
def f(v, n=3):
    s = f"{v:.{n}f}".rstrip("0").rstrip(".")
    return s
VB = f"0 0 {f(W)} {f(H)}"
def sub(path, pairs):
    p = REPO + path; s = open(p).read()
    for a, b, *cnt in pairs:
        n = s.count(a) if isinstance(a, str) else len(re.findall(a, s))
        want = cnt[0] if cnt else 1
        assert n == want, (path, a if isinstance(a, str) else a.pattern, n)
        s = s.replace(a, b) if isinstance(a, str) else a.sub(lambda m: b, s)
    open(p, "w").write(s)

# 1. af-build.css: the generated build
open(REPO + "src/app/af-build.css", "w").write(open("af.css").read())

# 2. AFBuild.tsx: letters, hexagon, cut, mask, viewBox, the generated construction
p = REPO + "src/components/AFBuild.tsx"; s = open(p).read()
letters = "export const LETTERS: [string, string][] = [\n" + "".join(f'  ["{k}", "{d}"],\n' for k, d in LETTERS) + "]\n"
s = re.sub(r"export const LETTERS: \[string, string\]\[\] = \[\n.*?\n\]\n", lambda m: letters, s, count=1, flags=re.S)
s = re.sub(r'export const HEX = "[^"]*"', f'export const HEX = "{HEX}"', s)
s = re.sub(r'export const CUT = "[^"]*"', f'export const CUT = "{CUT}"', s)
mask = dict(x=round(HL - 60, 3), y=-60, width=round(HR - HL + 120, 3), height=220)
s = re.sub(r"export const MASK = \{[^}]*\}", "export const MASK = { x: %s, y: -60, width: %s, height: 220 }" % (f(mask["x"]), f(mask["width"])), s)
i = s.index("/* generated by the blueprint kit"); j = s.index("export function AFBuild")
s = s[:i] + open("cons.tsx").read().split("\n", 0)[0].rstrip() + "\n\n" + s[j:]
s = re.sub(r'viewBox="0 0 [\d.]+ [\d.]+"', f'viewBox="{VB}"', s)
open(p, "w").write(s)

# 3. AFStory.tsx: centre, radii, the small mark's viewBox, masks round the hexagon, the travellers' boxes
mx = math.floor(HL) - 14; mw = math.ceil(HR) + 14 - mx
p = REPO + "src/components/AFStory.tsx"; s = open(p).read()
s = re.sub(r"const CX = [\d.]+", f"const CX = {f(CX)}", s)
s = re.sub(r"const CY = [\d.]+", f"const CY = {f(CY)}", s)
s = re.sub(r"const R = [\d.]+", f"const R = {f(R)}", s)
s = re.sub(r"const RD = [\d.]+", f"const RD = {f(D)}", s)
s = re.sub(r'viewBox="0 0 [\d.]+ [\d.]+"', f'viewBox="{VB}"', s)
s = re.sub(r'maskUnits="userSpaceOnUse" x="\d+" y="-14" width="\d+" height="128"', f'maskUnits="userSpaceOnUse" x="{mx}" y="-14" width="{mw}" height="128"', s)
s = re.sub(r'<rect x="\d+" y="-14" width="\d+" height="128"', f'<rect x="{mx}" y="-14" width="{mw}" height="128"', s)
s = re.sub(r'viewBox="[\d.]+ 0 [\d.]+ 100"', f'viewBox="{f(HL)} 0 {f(HR - HL)} 100"', s)
s = re.sub(r'viewBox="[\d.]+ [\d.]+ [\d.]+ [\d.]+"(?=[^>]*>\s*(<path className="tk-fill" d=\{CUT\}|<path d=\{CUT\}))',
           f'viewBox="{f(CX - D)} {f(CY - D)} {f(2 * D)} {f(2 * D)}"', s)
open(p, "w").write(s)
assert s.count(f'viewBox="{f(CX - D)} {f(CY - D)}') == 2, "traveller viewBoxes"

# 4. o-story.css: the O slot in cqw of the wordmark's box, the small mark's O offset
cq = lambda v: f"{100 * v / W:.4f}cqw"
TSRC = 176  # .tk-src width, px
off = round(TSRC * (0.5 - CX / W), 1)
p = REPO + "src/app/o-story.css"; s = open(p).read()
s = re.sub(r"\(254\.333\.\.369\.781 x 0\.\.100 of\n   869\.023 x 101\.332\)", f"({f(HL)}..{f(HR)} x 0..100 of\n   {f(W)} x {f(H)})", s)
s = re.sub(r"--wmh:[\d.]+cqw", f"--wmh:{cq(H)}", s)
s = re.sub(r"--hexb:calc\(var\(--art-top\) \+ [\d.]+cqw\)", f"--hexb:calc(var(--art-top) + {cq(100)})", s)
s = re.sub(r"--ocx:[\d.]+cqw", f"--ocx:{cq(CX)}", s)
s = re.sub(r"left:calc\([\d.]+cqw - var\(--sx\)\);top:calc\(var\(--art-top\) - var\(--sy\)\);width:[\d.]+cqw",
           f"left:calc({cq(HL)} - var(--sx));top:calc(var(--art-top) - var(--sy));width:{cq(HR - HL)}", s)
s = re.sub(r"its O sits [\d.]+ px left of the axis", f"its O sits {off:g} px left of the axis", s)
rule = round(off + 0.5, 1)  # the rule's 1px border sits right of its left edge: centre it on the O
s = re.sub(r"left:calc\(50% - [\d.]+px\);width:[\d.]+px;height:20px", f"left:calc(50% - {rule:g}px);width:{rule:g}px;height:20px", s)
s = re.sub(r"steps across to the axis and drops, as the desktop leader does \*/", "steps across to the axis and drops, as the desktop leader does (its 1px line centred on the O) */", s)
open(p, "w").write(s)

print(dict(VB=VB, off=off, O_left=cq(HL), O_w=cq(HR - HL), wmh=cq(H), hexb=cq(100), ocx=cq(CX), mask=(mx, mw)))
